# 样本数量

vbar = [
    0.039
    , 0
    , 0.047
    , 0.054
    , 0.0511
    , 0.1101
    , 0.3198
    , 0.4899
    , 0.5809
    , 0.4882
    , 0.3542
    , 0.2801
    , 0.2206
        ]

        # 第二列：侧扫雷达水面平均流速Vr，作为x
vr = [
    -0.0072
    , 0.0072
    , 0.0048
    , -0.0040
    , 0.0071
    , 0.1710
    , 0.2126
    , 0.2754
    , 0.3801
    , 0.5267
    , 0.3465
    , 0.2598
    , 0.2108
]

n = len(vr)

# 检查两组数据数量是否相同
if len(vr) != len(vbar):
    raise ValueError("Vr和Vbar的数据数量不一致！")

# ==========================================================
# 第一步：计算最小二乘公式需要的中间量
# ==========================================================

# Σx：所有Vr相加
sum_x = sum(vr)

# Σy：所有Vbar相加
sum_y = sum(vbar)

# Σ(x²)：每个Vr平方后相加
sum_x2 = sum(x * x for x in vr)

# Σ(xy)：每个Vr与对应Vbar相乘后相加
sum_xy = sum(x * y for x, y in zip(vr, vbar))

# 斜率和截距公式的共同分母
denominator = n * sum_x2 - sum_x * sum_x

if denominator == 0:
    raise ValueError("拟合分母为0，无法计算斜率和截距！")

# ==========================================================
# 第二步：计算斜率a
#
#     NΣ(xy) - ΣxΣy
# a = ----------------
#      NΣ(x²) - (Σx)²
# ==========================================================

a = (n * sum_xy - sum_x * sum_y) / denominator

# ==========================================================
# 第三步：计算截距b
#
#     Σ(x²)Σy - ΣxΣ(xy)
# b = -------------------
#       NΣ(x²) - (Σx)²
# ==========================================================

b = (sum_x2 * sum_y - sum_x * sum_xy) / denominator

# ==========================================================
# 第四步：输出中间计算结果
# ==========================================================

print("样本数量 N =", n)
print("Σx          =", format(sum_x, ".12f"))
print("Σy          =", format(sum_y, ".12f"))
print("Σ(x²)       =", format(sum_x2, ".12f"))
print("Σ(xy)       =", format(sum_xy, ".12f"))
print("计算分母    =", format(denominator, ".12f"))

print("\n拟合参数：")
print("斜率 a =", format(a, ".12f"))
print("截距 b =", format(b, ".12f"))

print("\n最终拟合关系：")
print(f"Vbar = {a:.6f} × Vr + {b:.6f}")

# ==========================================================
# 第五步：计算每个样本的拟合值和误差
# ==========================================================

print("\n逐个样本计算结果：")
print("序号      Vr          Vbar        拟合Vbar       误差")

# 用于累计残差平方和
sse = 0.0

for i, (x, y) in enumerate(zip(vr, vbar), start=1):

    # 根据拟合关系计算Vbar
    fitted_vbar = a * x + b

    # 残差 = 实际Vbar - 拟合Vbar
    error = y - fitted_vbar

    # 累加残差平方
    sse += error ** 2

    print(
        f"{i:2d}   "
        f"{x:10.6f}  "
        f"{y:10.6f}  "
        f"{fitted_vbar:10.6f}  "
        f"{error:10.6f}"
    )

# ==========================================================
# 第六步：计算误差指标
# ==========================================================

# Python自带的math库，不需要额外安装
import math

# 均方根误差
rmse = math.sqrt(sse / n)

# Vbar平均值
mean_y = sum_y / n

# 总离差平方和
sst = sum((y - mean_y) ** 2 for y in vbar)

# 带截距拟合的决定系数
r2 = 1 - sse / sst

print("\n误差统计：")
print("残差平方和 SSE =", format(sse, ".12f"))
print("均方根误差 RMSE =", format(rmse, ".12f"), "m/s")
print("决定系数 R² =", format(r2, ".12f"))